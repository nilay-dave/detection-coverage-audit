"""Measure audit runtime and the headline coverage number across corpus sizes.

Writes raw results to benchmark/results/ as JSON. Every number the README
publishes about performance comes from a run of this file, and
tools/check_numbers.py fails CI when the README drifts from it.

Usage:
    python benchmark/run_benchmark.py [--sizes 100000 1000000 10000000]
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from dca.audit.engine import audit  # noqa: E402
from dca.config import Config  # noqa: E402
from dca.logging import configure  # noqa: E402
from dca.telemetry.generator import generate  # noqa: E402
from dca.telemetry.profile import profile_corpus  # noqa: E402

RESULTS = Path(__file__).parent / "results"
DEFAULT_SIZES = (100_000, 1_000_000, 10_000_000)
REPEATS = 3


def _hardware() -> dict:
    import os

    return {
        "platform": platform.platform(),
        "python": platform.python_version(),
        "processor": platform.machine(),
        "cpu_count": os.cpu_count(),
    }


def _time(fn, repeats: int = REPEATS) -> dict:
    samples = []
    value = None
    for _ in range(repeats):
        start = time.perf_counter()
        value = fn()
        samples.append(time.perf_counter() - start)
    samples.sort()
    return {
        "value": value,
        "repeats": repeats,
        "min_s": round(samples[0], 4),
        "median_s": round(statistics.median(samples), 4),
        "max_s": round(samples[-1], 4),
    }


def run(sizes: tuple[int, ...], repeats: int, rules_dir: Path, workdir: Path, reuse: bool = False) -> dict:
    configure("WARNING")
    config = Config()
    workdir.mkdir(parents=True, exist_ok=True)
    scenarios = []

    for size in sizes:
        corpus = workdir / f"bench_{size}.parquet"
        if reuse and corpus.exists():
            gen = {"repeats": 0, "min_s": None, "median_s": None, "max_s": None, "reused": True}
        else:
            gen = _time(lambda c=corpus, n=size: generate(c, n, seed=7).events, repeats=1)
            gen.pop("value", None)
        prof = _time(lambda c=corpus: profile_corpus(c, config), repeats=repeats)
        profile = prof.pop("value")
        aud = _time(lambda pr=profile: audit(rules_dir, pr, config), repeats=repeats)
        result = aud.pop("value")

        scenarios.append({
            "events": size,
            "corpus_bytes": corpus.stat().st_size,
            "generate": gen,
            "profile": prof,
            "audit": aud,
            "end_to_end_median_s": round(prof["median_s"] + aud["median_s"], 4),
            "events_per_second": round(size / (prof["median_s"] + aud["median_s"])),
            "distinct_fields_observed": sum(len(profile.fields_for(s)) for s in profile.observed_sources),
            "sources_observed": len(profile.observed_sources),
            "rules_audited": result.rule_count,
            "techniques_mapped": result.mapped_technique_count,
            "techniques_blind": len(result.blind_techniques),
            "blind_technique_pct": round(result.blind_technique_pct, 2),
            "verdict_counts": {v.value: result.count(v) for v in type(result.findings[0].verdict)},
        })
        if not reuse:
            corpus.unlink(missing_ok=True)
        print(
            f"  {size:>12,} events  profile {prof['median_s']:>7.3f}s  "
            f"audit {aud['median_s']:>7.3f}s  blind {result.blind_technique_pct:.1f}%"
        )

    return {
        "hardware": _hardware(),
        "repeats": repeats,
        "rules_dir": str(rules_dir),
        "corpus": "synthetic, generated by dca generate-telemetry at seed 7",
        "scenarios": scenarios,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sizes", type=int, nargs="+", default=list(DEFAULT_SIZES))
    parser.add_argument("--repeats", type=int, default=REPEATS)
    parser.add_argument("--rules", type=Path, default=Path(__file__).resolve().parents[1] / "rules")
    parser.add_argument("--workdir", type=Path, default=Path("data/generated/bench"))
    parser.add_argument(
        "--reuse", action="store_true", help="Reuse and keep corpora in workdir instead of regenerating."
    )
    args = parser.parse_args()

    print(f"benchmarking {len(args.sizes)} corpus sizes, {args.repeats} repeats each")
    payload = run(tuple(args.sizes), args.repeats, args.rules, args.workdir, reuse=args.reuse)

    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / "benchmark.json"
    out.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
