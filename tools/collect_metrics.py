"""Collect every number this repository publishes into docs/metrics.json.

The README, the badges and the explainer video all read their numbers from this
file rather than carrying their own copies. tools/check_numbers.py then fails CI
when a published number no longer matches a measured one. The point is that a
number in this repository cannot silently go stale.

Usage:
    python tools/collect_metrics.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from dca.audit.engine import Verdict, audit  # noqa: E402
from dca.config import Config  # noqa: E402
from dca.logging import configure  # noqa: E402
from dca.telemetry.generator import generate  # noqa: E402
from dca.telemetry.profile import profile_corpus  # noqa: E402

BENCHMARK = ROOT / "benchmark" / "results" / "benchmark.json"
COVERAGE_XML = ROOT / "coverage.xml"
OUT = ROOT / "docs" / "metrics.json"
HEADLINE_EVENTS = 1_000_000
HEADLINE_SEED = 7


def _coverage_pct() -> float | None:
    """Read the line rate pytest-cov wrote to coverage.xml."""
    if not COVERAGE_XML.exists():
        return None
    root = ET.parse(COVERAGE_XML).getroot()
    rate = root.get("line-rate")
    return round(float(rate) * 100, 1) if rate else None


def _test_count() -> int | None:
    """Count collected tests.

    Parses the per file counts that `pytest --collect-only -q` prints, which is
    stable across pytest versions. An earlier version of this function looked
    for a summary line containing the word "collected", which this pytest does
    not print, so the metric silently recorded null.
    """
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q"],
        cwd=ROOT, capture_output=True, text=True,
    )
    total = 0
    for line in result.stdout.splitlines():
        head, _, tail = line.rpartition(":")
        if head.endswith(".py") and tail.strip().isdigit():
            total += int(tail.strip())
    return total or None


def _git_commit_count() -> int | None:
    result = subprocess.run(
        ["git", "rev-list", "--count", "HEAD"], cwd=ROOT, capture_output=True, text=True
    )
    return int(result.stdout.strip()) if result.returncode == 0 else None


def _headline_audit() -> dict:
    """Re-run the audit that the README's headline number comes from."""
    configure("WARNING")
    config = Config()
    corpus = ROOT / "data" / "generated" / f"metrics_{HEADLINE_EVENTS}.parquet"
    if not corpus.exists():
        generate(corpus, HEADLINE_EVENTS, seed=HEADLINE_SEED)
    profile = profile_corpus(corpus, config)
    result = audit(ROOT / "rules", profile, config)
    return {
        "corpus_events": HEADLINE_EVENTS,
        "corpus_seed": HEADLINE_SEED,
        "corpus_kind": "synthetic",
        "rules_audited": result.rule_count,
        "rules_unparseable": result.unparseable_count,
        "log_sources_observed": len(result.observed_sources),
        "distinct_fields_observed": sum(
            len(profile.fields_for(source)) for source in profile.observed_sources
        ),
        "techniques_mapped": result.mapped_technique_count,
        "techniques_blind": len(result.blind_techniques),
        "blind_technique_pct": round(result.blind_technique_pct, 1),
        "verdict_counts": {verdict.value: result.count(verdict) for verdict in Verdict},
    }


def main() -> int:
    payload: dict = {
        "note": (
            "Generated by tools/collect_metrics.py. Numbers derived from the bundled "
            "synthetic corpus are simulations and are labelled as such wherever they "
            "are published."
        ),
        "audit": _headline_audit(),
        "quality": {
            "test_coverage_pct": _coverage_pct(),
            "test_count": _test_count(),
            "commit_count": _git_commit_count(),
        },
    }

    if BENCHMARK.exists():
        benchmark = json.loads(BENCHMARK.read_text(encoding="utf-8"))
        payload["performance"] = {
            "hardware": benchmark["hardware"],
            "repeats": benchmark["repeats"],
            "scenarios": [
                {
                    "events": scenario["events"],
                    "corpus_mb": round(scenario["corpus_bytes"] / 1e6, 1),
                    "profile_median_s": scenario["profile"]["median_s"],
                    "audit_median_s": scenario["audit"]["median_s"],
                    "end_to_end_median_s": scenario["end_to_end_median_s"],
                    "events_per_second": scenario["events_per_second"],
                }
                for scenario in benchmark["scenarios"]
            ],
        }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    print(json.dumps(payload["audit"], indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
